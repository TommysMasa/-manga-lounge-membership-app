// ============================================================================
// FIREBASE PROVIDERS (Shared across features)
// ============================================================================

/// Firebase Auth Provider
final firebaseAuthProvider = Provider<firebase_auth.FirebaseAuth>((ref) {
  return firebase_auth.FirebaseAuth.instance;
});

/// Firestore Provider
final firestoreProvider = Provider<FirebaseFirestore>((ref) {
  return FirebaseFirestore.instance;
});

// ============================================================================
// USER FEATURE PROVIDERS
// ============================================================================

/// User Data Source Provider
/// Provides Firestore implementation of UserDataSource
final userDataSourceProvider = Provider<UserDataSource>((ref) {
  return UserDataSourceImpl(
    firestore: ref.watch(firestoreProvider),
    auth: ref.watch(firebaseAuthProvider),
  );
});

/// User Repository Provider
/// Provides implementation of UserRepository using UserDataSource
final userRepositoryProvider = Provider<UserRepository>((ref) {
  return UserRepositoryImpl(ref.watch(userDataSourceProvider));
});

// ============================================================================
// USER USE CASE PROVIDERS
// ============================================================================

/// CreateUserProfile Use Case Provider
final createUserProfileProvider = Provider<CreateUserProfile>((ref) {
  return CreateUserProfile(ref.watch(userRepositoryProvider));
});

/// GetUser Use Case Provider
final getUserProvider = Provider<GetUser>((ref) {
  return GetUser(ref.watch(userRepositoryProvider));
});

/// GetCurrentUser Use Case Provider
final getCurrentUserProvider = Provider<GetCurrentUser>((ref) {
  return GetCurrentUser(ref.watch(userRepositoryProvider));
});

/// UpdateUserProfile Use Case Provider
final updateUserProfileProvider = Provider<UpdateUserProfile>((ref) {
  return UpdateUserProfile(ref.watch(userRepositoryProvider));
});

/// CheckUserProfileExists Use Case Provider
final checkUserProfileExistsProvider = Provider<CheckUserProfileExists>((ref) {
  return CheckUserProfileExists(ref.watch(userRepositoryProvider));
});

/// WatchUser Use Case Provider
final watchUserProvider = Provider<WatchUser>((ref) {
  return WatchUser(ref.watch(userRepositoryProvider));
});

/// UpdateUserStatus Use Case Provider
final updateUserStatusProvider = Provider<UpdateUserStatus>((ref) {
  return UpdateUserStatus(ref.watch(userRepositoryProvider));
});

